$purchase_id = isset($_GET['id']) ? (int)$_GET['id'] : 0;
if ($purchase_id <= 0) die("Invalid Purchase ID");

$stmt = $pdo->prepare("
    SELECT p.*, s.supplier_name, s.address as sup_address, s.phone as sup_phone, s.gst_number as sup_gst,
           u.full_name as created_by 
    FROM purchases p
    LEFT JOIN suppliers s ON p.supplier_id = s.id
    LEFT JOIN users u ON p.user_id = u.id
    WHERE p.id = ? AND p.branch_id = ?
");
$stmt->execute([$purchase_id, $_SESSION['branch_id'] ?? 1]);
$purchase = $stmt->fetch();

if (!$purchase) die("Purchase Bill not found.");

$stmtItems = $pdo->prepare("
    SELECT pi.*, pr.product_name, pr.hsn_code, u.unit_name 
    FROM purchase_items pi
    JOIN products pr ON pi.product_id = pr.id
    LEFT JOIN units u ON pr.unit_id = u.id
    WHERE pi.purchase_id = ?
");
$stmtItems->execute([$purchase_id]);
$items = $stmtItems->fetchAll();

